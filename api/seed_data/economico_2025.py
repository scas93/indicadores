def rangos_inferidos(pares: list[tuple[float, str]], eps: float = 1) -> dict:
    """Un intervalo por color (± `eps` alrededor de los valores que deben caer ahí); gris = ningún intervalo."""
    out: dict = {}
    for color in ("verde", "amarillo", "rojo"):
        vals = [v for v, c in pares if c == color]
        if vals:
            out[color] = {"desde": min(vals) - eps, "hasta": max(vals) + eps}
    return out


def _consistentes(pares: list[tuple[float, str]], rg: dict) -> bool:
    """Sin traslape y cada valor cae en su color (el primer rango que lo contiene: verde, amarillo, rojo)."""
    orden = ("verde", "amarillo", "rojo")
    its = [rg[c] for c in orden if c in rg]
    if any(not (a["hasta"] < b["desde"] or b["hasta"] < a["desde"]) for k, a in enumerate(its) for b in its[k + 1:]):
        return False
    for v, esperado in pares:
        got = next((c for c in orden if c in rg and rg[c]["desde"] <= v <= rg[c]["hasta"]), "gris")
        if got != esperado:
            return False
    return True


def rangos_de(ind: dict) -> dict:
    """Rangos reales (410, 411) o INFERIDOS del indicador: reproducen sus 4 resultados verificados en la referencia
    (2025 y 2024, Cumplimiento Obtenido y C.O/C.E). El primer `eps` que no se traslapa es el que se usa."""
    if ind["ref"] == "410":
        return R410
    if ind["ref"] == "411":
        return R411
    pares = [(ind["alcanzada"], ind["color_obtenido"]), (ind["avance"], ind["color_co_ce"]),
             (ind["alcanzada_2024"], ind["color_obtenido_2024"]), (ind["avance_2024"], ind["color_co_ce_2024"])]
    for eps in (1, 0.5, 0.1, 0.01):
        rg = rangos_inferidos(pares, eps)
        if _consistentes(pares, rg):
            return rg
    raise ValueError(f"Sin rangos consistentes para el indicador {ind['id']}")


